"""Renders each Alembic revision to the SQL statements it runs on SQLite, offline, into the orders-core
package's orders_core/migrations_sql.py, which the migrate function ships (funcd ADR-0236 Decision 5).
Alembic's own transaction and alembic_version statements are left out: the migrate function runs each
revision's statements in one call and records it in _migrations.

    uv run python scripts/render_migrations.py           # rewrite orders_core/migrations_sql.py
    uv run python scripts/render_migrations.py --check   # fail when it is stale
"""

import io
import json
import sys
from pathlib import Path

from alembic.config import Config
from alembic.script import ScriptDirectory

from alembic import command

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "packages" / "orders-core" / "src" / "orders_core" / "migrations_sql.py"


def statements(cfg: Config, revision: str, previous: str | None) -> list[str]:
    buf = io.StringIO()
    cfg.output_buffer = buf
    command.upgrade(cfg, f"{previous}:{revision}" if previous else revision, sql=True)
    out = []
    for chunk in buf.getvalue().split(";\n"):
        lines = [line for line in chunk.splitlines() if line.strip() and not line.startswith("--")]
        stmt = "\n".join(lines).strip()
        if stmt and stmt not in ("BEGIN TRANSACTION", "COMMIT") and "alembic_version" not in stmt:
            out.append(stmt)
    return out


def render() -> str:
    cfg = Config(str(ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(ROOT / "alembic"))
    revisions = list(reversed(list(ScriptDirectory.from_config(cfg).walk_revisions())))
    body = [
        '"""Generated by scripts/render_migrations.py from alembic/versions: do not edit."""',
        "",
        "# ruff: noqa: E501",
        "",
    ]
    body.append("MIGRATIONS: dict[str, list[str]] = {")
    previous = None
    for rev in revisions:
        body.append(f"    {json.dumps(rev.revision)}: [")
        body += [f"        {json.dumps(s)}," for s in statements(cfg, rev.revision, previous)]
        body.append("    ],")
        previous = rev.revision
    body.append("}")
    return "\n".join(body) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit("orders_core/migrations_sql.py is stale: run scripts/render_migrations.py")
    else:
        OUT.write_text(text)
